const fs = require('node:fs');
const http = require('node:http');
const path = require('node:path');
const { chromium } = require('/Users/lertoon/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const dir = '/tmp/ear-refine-fixes-20261016';
const repo = '/Users/lertoon/vscProjects/EAR-Audio-Preview';
const server = http.createServer((req, res) => {
  if (req.url === '/') return res.end('<!doctype html><script src="/test.js"></script>');
  const base = req.url === '/loudness.worklet.js' ? repo + '/dist' : dir + '/browser-dist';
  const file = path.join(base, path.basename(req.url));
  if (!fs.existsSync(file)) return res.writeHead(404).end();
  res.setHeader('Content-Type', file.endsWith('.wasm') ? 'application/wasm' : 'text/javascript');
  fs.createReadStream(file).pipe(res);
});
(async () => {
  await new Promise(r => server.listen(0, '127.0.0.1', r));
  const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--autoplay-policy=no-user-gesture-required', '--mute-audio'] });
  try {
    const page = await browser.newPage();
    const errors=[];
    page.on('pageerror', e=>errors.push(String(e)));
    await page.goto(`http://127.0.0.1:${server.address().port}`);
    await page.waitForFunction(()=>window.reviewApi);
    const result=await page.evaluate(async()=>{
      const a=window.reviewApi;
      a.setLoudnessWorkletModuleUrl('/loudness.worklet.js');
      const check=(ok,message)=>{if(!ok) throw new Error(message);};
      const delay=ms=>new Promise(r=>setTimeout(r,ms));
      const ctx=new AudioContext({sampleRate:48000});
      await ctx.resume();
      const buffer=ctx.createBuffer(2,48000*8,48000);
      for(let c=0;c<2;c++) for(let i=0;i<buffer.length;i++) buffer.getChannelData(c)[i]=.2*Math.sin(2*Math.PI*1000*i/48000);
      const settings=a.PlayerSettingsService.fromDefaultSetting({},buffer);
      const analyze=a.AnalyzeSettingsService.fromDefaultSetting({hearingProtectionEnabled:false},buffer);
      const player=new a.PlayerService(ctx,buffer,settings,analyze);
      const sources=[];
      const original=ctx.createBufferSource.bind(ctx);
      ctx.createBufferSource=()=>{const source=original();sources.push(source);return source;};
      player.setPlaybackPosition(2);
      player.play();
      await delay(180);
      const clockBefore=ctx.currentTime;
      analyze.showLiveAnalysis=true;
      analyze.showLevelMeter=true;
      await delay(180);
      check(sources.length===1,'Live display recreated source');
      check(player.playbackPosition===2,'Live display changed cue');
      check(ctx.currentTime>clockBefore,'Audio clock stopped');
      analyze.showLiveAnalysis=false;
      analyze.showLevelMeter=false;
      analyze.liveMonitoringMode='s';
      check(player.getAnalysers()!==null,'Hidden Monitor failed to create graph');
      analyze.liveMonitoringMode='lr';
      check(player.getAnalysers()===null,'Default Monitor retained unnecessary graph');
      analyze.monitorBandSoloMask=1;
      check(player.getAnalysers()!==null,'Band solo failed to create graph');
      analyze.monitorBandSoloMask=0;
      check(player.getAnalysers()===null,'Band reset retained graph');
      check(sources.length===1,'Routing recreated the playing source');
      const edit=a.EditExportSettingsService.create(buffer);
      edit.setRegion(1,3);
      const listen=new a.EditListenService(buffer,edit,settings,analyze,player);
      listen.enter();
      check(sources.length===2,'Entering Edit did not replace old source');
      check(sources[1].loop && sources[1].loopStart===1 && sources[1].loopEnd===3,'Edit loop region incorrect');
      check(player.isPlaying && player.editListenActive,'Edit playback not restored');
      listen.dispose();player.dispose();
      const boundary=[];
      for(const [rate,length] of [[44100,44109],[48000,48005],[96000,96001]]) {
        const ref=new AudioBuffer({numberOfChannels:2,length,sampleRate:rate});
        const candidate=new AudioBuffer({numberOfChannels:2,length,sampleRate:rate});
        ref.getChannelData(0)[length-1]=1;ref.getChannelData(1)[length-1]=1;
        const range=a.commonMeasurementRange([ref,candidate],{start:0,end:ref.duration});
        const rms=await a.measureRms(ref,range);
        const residual=await a.measureResidual(ref,candidate,range);
        check(Math.abs(rms-1/Math.sqrt(length))<1e-14,'RMS omitted last frame');
        check(residual.frames===length && residual.peakDbfs===0,'Residual omitted last frame');
        boundary.push({rate,length,rms,residual});
      }
      // Render the actual hidden-monitor path: identical L/R must cancel in Side.
      const render=async mode=>{
        const offline=new OfflineAudioContext(2,4800,48000);
        const signal=offline.createBuffer(2,4800,48000);
        for(let ch=0;ch<2;ch++) for(let i=0;i<4800;i++) signal.getChannelData(ch)[i]=.25*Math.sin(2*Math.PI*1000*i/48000);
        const config=a.AnalyzeSettingsService.fromDefaultSetting({hearingProtectionEnabled:false},signal);
        config.liveMonitoringMode=mode;
        const playback=new a.PlayerService(offline,signal,a.PlayerSettingsService.fromDefaultSetting({},signal),config);
        playback.play();
        const output=await offline.startRendering();
        let energy=0;for(const v of output.getChannelData(0))energy+=v*v;
        playback.dispose();
        return Math.sqrt(energy/output.length);
      };
      const stereoRms=await render('lr');
      const sideRms=await render('s');
      check(stereoRms>.1 && sideRms<1e-7,'Hidden Side monitor did not cancel equal channels: stereo='+stereoRms+' side='+sideRms);
      return {sourceCountAfterLiveToggle:1,sourceCountAfterEdit:sources.length,cue:2,monitorGraphTransitions:'passed',nativeRenderedMonitor:{stereoRms,sideRms},boundary};
    });
    if(errors.length) throw new Error(errors.join('\n'));
    fs.writeFileSync(dir+'/browser-results.json',JSON.stringify({status:'passed',browser:await browser.version(),...result,pageErrors:errors},null,2));
    console.log(JSON.stringify(result,null,2));
  } finally {await browser.close();await new Promise(r=>server.close(r));}
})().catch(e=>{console.error(e);server.close();process.exitCode=1;});
